/// Nombre de la categoría por defecto que mejor encaja con un nombre de
/// alimento o de artículo ("Pechuga de pollo" → Carnicería). Null si no se
/// reconoce. Las frases tienen prioridad sobre las palabras sueltas; entre
/// palabras, gana la categoría con más coincidencias (y a igualdad, la
/// primera palabra del nombre: "Leche de coco" → Lácteos).
String? guessCategoryName(String nombre) {
  final norm = normalizeText(nombre);
  if (norm.isEmpty) return null;
  for (final c in defaultCategories) {
    for (final f in c.frases) {
      if (' $norm '.contains(' ${normalizeText(f)} ')) return c.nombre;
    }
  }
  final palabras = [
    for (final w in norm.split(' '))
      if (w.isNotEmpty) singularize(w),
  ];
  String? mejor;
  var mejorScore = 0;
  var mejorPos = 1 << 30;
  for (final c in defaultCategories) {
    var score = 0;
    var pos = 1 << 30;
    for (var i = 0; i < palabras.length; i++) {
      final w = palabras[i];
      if (c.palabras.contains(w) || c.palabras.contains(norm.split(' ')[i])) {
        score++;
        if (i < pos) pos = i;
      }
    }
    if (score == 0) continue;
    if (score > mejorScore || (score == mejorScore && pos < mejorPos)) {
      mejor = c.nombre;
      mejorScore = score;
      mejorPos = pos;
    }
  }
  return mejor;
}
